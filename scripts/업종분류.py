# ②-2 공정위 가맹사업 브랜드 사전(공정위_브랜드사전.csv, 같은 폴더). 없으면 건너뛴다.
def _norm(t):
    return re.sub(r"[\s\(\)\[\]&·\.\-,'/]", "", t or "").lower()

def _load_ftc():
    import csv
    from pathlib import Path
    f = Path(__file__).with_name("공정위_브랜드사전.csv")
    if not f.exists():
        return []
    with open(f, encoding="utf-8-sig") as fp:
        rows = [(r["브랜드_정규화"], r["업종"]) for r in csv.DictReader(fp)]
    return sorted(rows, key=lambda x: len(x[0]), reverse=True)   # 긴 이름부터 맞춘다

FTC = _load_ftc()

def ftc_lookup(shop_name):
    """상호가 브랜드명으로 시작하면 그 브랜드의 업종. (가운데 포함은 오판정이 많아 쓰지 않는다)"""
    n = _norm(shop_name)
    for b, cat in FTC:
        if n.startswith(b):
            return cat
    return None

def classify(type_name, shop_name):
    type_name = (type_name or "").strip()
    name = shop_name or ""
    if type_name in TYPE_MAP:
        return TYPE_MAP[type_name], "업태"
    low = name.lower().replace(" ", "")
    for b, cat in BRAND_INDEX:
        if b.replace(" ", "") in low:
            return cat, "프랜차이즈"
    for cat, pat in RULES:
        if pat.search(name):
            return cat, "상호 키워드"
    cat = ftc_lookup(name)          # 키워드로 못 정한 것만 공정위 사전으로 채운다(공정위 '한식'은 범위가 넓어서)
    if cat:
        return cat, "공정위 브랜드"
    return "기타", "미분류"
